package com.robin.tools.core.ui

import androidx.compose.ui.unit.dp

/**
 * Spacing tokens for consistent layout across all screens.
 * Usage: Modifier.padding(Dimension.lg) or Arrangement.spacedBy(Dimension.md)
 */
object Dimension {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
    val xxxl = 48.dp
}
